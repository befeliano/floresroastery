/** WooCommerce adresindeki il ("TR26" ya da "Eskişehir") → listedeki il adı */
export function cityFromWooState(state: string | undefined): string {
  if (!state) return "";
  const code = /^TR(\d{2})$/.exec(state.trim());
  if (code) return TR_PLATE[Number(code[1]) - 1] ?? "";
  const s = state.trim().toLocaleLowerCase("tr-TR");
  return TR_CITIES.find((c) => c.toLocaleLowerCase("tr-TR") === s) ?? "";
}

/** İl adı → WooCommerce il kodu ("Eskişehir" → "TR26"); bulunamazsa adın kendisi */
export function wooStateFromCity(city: string): string {
  const i = TR_PLATE.indexOf(city.trim());
  return i < 0 ? city : `TR${String(i + 1).padStart(2, "0")}`;
}
